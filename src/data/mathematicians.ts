export const getMathematician = (slug: string) =>
  mathematicians.find((m) => m.slug === slug);

export const getNeighbors = (slug: string) => {
  const idx = mathematicians.findIndex((m) => m.slug === slug);
  if (idx === -1) return { prev: undefined, next: undefined };
  const prev = mathematicians[(idx - 1 + mathematicians.length) % mathematicians.length];
  const next = mathematicians[(idx + 1) % mathematicians.length];
  return { prev, next };
};